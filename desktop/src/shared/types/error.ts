/** 统一错误码 */
export enum ErrorCode {
  // 主系统 1000-1999
  MODULE_LOAD_FAILED = 1001,
  MODULE_DEPENDENCY_MISSING = 1002,
  MODULE_VERSION_INCOMPATIBLE = 1003,
  MODULE_ACTIVATE_TIMEOUT = 1004,
  MODULE_CIRCULAR_DEPENDENCY = 1005,

  // AI 调度器 2000-2999
  AI_INTENT_FAILED = 2001,
  AI_OLLAMA_UNAVAILABLE = 2002,
  AI_REQUEST_TIMEOUT = 2003,
  AI_RESPONSE_INVALID = 2004,

  // 屏幕理解 3000-3999
  SCREEN_CAPTURE_FAILED = 3001,
  SCREEN_ANALYSIS_TIMEOUT = 3002,
  SCREEN_PERMISSION_DENIED = 3003,

  // 鼠标键盘 4000-4999
  CONTROL_PERMISSION_DENIED = 4001,
  CONTROL_ACTION_FAILED = 4002,

  // 记忆系统 5000-5999
  MEMORY_STORAGE_FULL = 5001,
  MEMORY_WRITE_FAILED = 5004,
  MEMORY_READ_FAILED = 5005,
  MEMORY_NOT_FOUND = 5006,
  MEMORY_SEARCH_FAILED = 5002,
  MEMORY_EMBEDDING_FAILED = 5003,
  MEMORY_VEC_EXTENSION_UNAVAILABLE = 5010,
  MEMORY_ENCRYPTION_FAILED = 5020,
  MEMORY_DECRYPTION_FAILED = 5021,
  MEMORY_ENCRYPTION_KEY_MISSING = 5022,
  MEMORY_ACCESS_DENIED = 5030,
  MEMORY_SESSION_ISOLATION_VIOLATION = 5031,
  MEMORY_PERMISSION_DENIED = 5032,
  MEMORY_SUMMARY_FAILED = 5040,
  MEMORY_SUMMARY_PARSE_ERROR = 5041,
  MEMORY_CLEANUP_FAILED = 5050,
  MEMORY_MANAGER_DESTROYED = 5060,
  MEMORY_INVALID_PARAMS = 5061,

  // 通用 9000-9999
  INVALID_PARAMS = 9001,
  TIMEOUT = 9002,
  PERMISSION_DENIED = 9003,
  INTERNAL_ERROR = 9999
}

/** 统一错误类 */
export class AppError extends Error {
  constructor(
    public code: ErrorCode,
    message: string,
    public details?: unknown
  ) {
    super(message)
    this.name = 'AppError'
  }
}
